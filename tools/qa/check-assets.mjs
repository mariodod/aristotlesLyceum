/**
 * Proves that public/ is fully regenerable from tools/.
 *
 * Hashes every file under public/, runs `npm run assets`, hashes again and
 * reports any file that changed, appeared or disappeared. A hand-edited
 * asset is caught here rather than on a player's machine.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

function snapshot(root, dir = root, out = {}) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    const name = relative(root, path).replaceAll('\\', '/');

    if (statSync(path).isDirectory()) {
      snapshot(root, path, out);
    } else {
      out[name] = createHash('sha256').update(readFileSync(path)).digest('hex');
    }
  }

  return out;
}

const before = snapshot('public');

// Run the generators directly, so this works on every platform without
// depending on npm being on PATH.
for (const script of ['tools/assets/build-assets.mjs', 'tools/audio/build-audio.mjs']) {
  execFileSync(process.execPath, [script], { stdio: 'pipe' });
}

const after = snapshot('public');

const problems = [];

for (const name of new Set([...Object.keys(before), ...Object.keys(after)])) {
  if (!before[name]) {
    problems.push(`${name}: appeared without a generator`);
  } else if (!after[name]) {
    problems.push(`${name}: was not regenerated`);
  } else if (before[name] !== after[name]) {
    problems.push(`${name}: changed on regeneration`);
  }
}

if (problems.length > 0) {
  console.error(`Asset pack is not reproducible (${problems.length} problem(s)):`);
  for (const problem of problems) {
    console.error(`  - ${problem}`);
  }
  process.exit(1);
}

console.log(
  `Asset pack reproducible: ${Object.keys(after).length} files regenerated byte for byte.`,
);
